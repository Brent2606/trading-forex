/**
 * Translations. The interface is written in English; `tr()` turns a displayed English
 * string into Dutch when the language is "nl": exact strings first, then patterns for
 * messages that contain numbers or names. Unknown strings stay English. Common FX terms
 * that Dutch traders use as-is (stop loss, take profit, spread, pips, lots) stay English.
 */
export type Lang = 'en' | 'nl';

let lang: Lang = 'en';
export const getLang = (): Lang => lang;
export function setLang(l: Lang): void {
  lang = l;
}
export function detectLang(navigatorLang: string | undefined): Lang {
  return navigatorLang && /^nl\b/i.test(navigatorLang) ? 'nl' : 'en';
}

