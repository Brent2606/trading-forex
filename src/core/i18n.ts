/** True when Dutch has an entry or pattern for this English string. */
export function hasTranslation(text: string): boolean {
  if (NL[text] !== undefined) return true;
  return RULES.some(([re]) => re.test(text)) || looksLikeDesc(text);
}

/** Translates one displayed string (no-op in English). */
export function tr(text: string): string {
  if (lang === 'en' || !text) return text;
  const exact = NL[text];
  if (exact !== undefined) return exact;
  if (!/[A-Za-z]{2}/.test(text)) return text;
  for (const [re, fn] of RULES) {
    const m = text.match(re);
    if (m) return fn(...m.slice(1).map((g) => g ?? ''));
  }
  if (looksLikeDesc(text)) return desc(text);
  return text;
}

/** Translates each line of a multi-line message. */
export function trLines(text: string): string {
  if (lang === 'en') return text;
  return text
    .split('\n')
    .map((line) => {
      const m = line.match(/^(\s*)(.*)$/)!;
      return m[1] + tr(m[2]);
    })
    .join('\n');
}

