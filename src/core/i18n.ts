const dur = (s: string) => s.replace(/(\d+)h/g, '$1u');
const side = (s: string) => (s === 'BUY' ? 'KOOP' : s === 'SELL' ? 'VERKOOP' : s);

/** Strategy descriptions: "EMA 20/50 cross · SL 2×ATR · TP 3×ATR · EMA200 trend · ..." */
function desc(s: string): string {
  return s
    .split(' · ')
    .map((part) => {
      if (NL[part]) return NL[part];
      return part
        .replace(/ cross$/, '-kruising')
        .replace(/ reversion$/, '-terugkeer')
        .replace(/ breakout$/, '-uitbraak')
        .replace(/^no TP$/, 'geen TP')
        .replace(/ trend$/, '-trend')
        .replace(/^exit on flip$/, 'uit bij omslag')
        .replace(/^skip high vol$/, 'geen hoge vol.')
        .replace(/^skip low vol$/, 'geen lage vol.')
        .replace(/London\/NY overlap/g, 'overlap Londen/NY')
        .replace(/London/g, 'Londen')
        .replace(/Asia/g, 'Azië')
        .replace(/Late/g, 'Laat');
    })
    .join(' · ');
}

